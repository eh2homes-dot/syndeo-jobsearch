def test_same_board_spelled_differently_has_one_identity():
    old = B.Board("workday", "zillow", {"wd": "wd5", "site": "Zillow_Group_External"})
    new = B.classify("https://zillow.wd5.myworkdayjobs.com/en-US/Zillow_Group_External")
    assert old.identity() == new.identity()
    assert B.Board("lever", "Acme").identity() == B.Board("lever", "acme").identity()
    assert B.Board("greenhouse", "acme").identity() != B.Board("greenhouse", "acmeinc").identity()


