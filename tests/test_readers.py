"""Offline tests for the shared job-system readers (jobsearch/boards.py).

The important one is test_history_keys_are_unchanged: tests/fixtures/readers/
golden_keys.json holds the keys the two searches stored BEFORE the readers were
merged into one library (generated by running the old code against the same
fake answers). If a reader ever builds a different key, every tracked role
would look closed-and-reopened, so that must never drift.
"""
import json
import pathlib
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import fakenet                                    # noqa: E402
from jobsearch import adapters, boards as B       # noqa: E402
from jobsearch.http import FetchError, NotFound   # noqa: E402

ROUTES = json.loads((ROOT / "tests/fixtures/readers/payloads.json").read_text())
GOLDEN = json.loads((ROOT / "tests/fixtures/readers/golden_keys.json").read_text())

WEEKLY = {
    "greenhouse": ("acme", {}), "lever": ("acme", {}), "ashby": ("acme", {}), "workable": ("acme", {}),
    "smartrecruiters": ("Acme", {}), "bamboohr": ("acme", {}), "breezy": ("acme", {}),
    "recruitee": ("acme", {}), "rippling": ("acme", {}), "jobvite": ("acme-internal", {}),
    "workday": ("acme", {"wd": "wd5", "site": "External", "confidence": "html", "careers_url": "x"}),
}
OPCO = {
    "greenhouse": ("acme", {}), "lever": ("acme", {}), "ashby": ("acme", {}), "workable": ("acme", {}),
    "smartrecruiters": ("Acme", {}), "recruitee": ("acme", {}), "breezy": ("acme", {}), "bamboohr": ("acme", {}),
    "workday": ("acme", {"host": "acme.wd5.myworkdayjobs.com", "site": "External"}),
    "ukg": ("ACM1000ACME", {"host": "recruiting2.ultipro.com", "board": "82898216-ca7a-4621-b01b-bf3410c919b2"}),
    "adp": ("0b0b0b0b-1111-2222-3333-444444444444", {"cc": "19000101_000001"}),
    "dayforce": ("acme", {"board": "CANDIDATEPORTAL"}),
}


def test_history_keys_are_unchanged():
    with fakenet.serve(ROUTES):
        for name, (slug, kw) in WEEKLY.items():
            keys = sorted(j["job_key"] for j in adapters.ADAPTERS[name](slug, **kw))
            if name == "jobvite":      # now also reads page 2; the old keys must all still be there
                assert set(GOLDEN["weekly"][name]) <= set(keys), name
            else:
                assert keys == GOLDEN["weekly"][name], name
        for name, (slug, kw) in OPCO.items():
            ids = sorted(B.opco_id(j) for j in B.READERS[name](slug, **kw) if j["title"])
            assert ids == GOLDEN["opco"][name], name


def test_every_job_has_title_and_direct_link():
    with fakenet.serve(ROUTES):
        for name, (slug, kw) in {**OPCO, "rippling": ("acme", {}), "jobvite": ("acme-internal", {})}.items():
            for j in B.READERS[name](slug, **kw):
                if j["title"]:
                    assert j["url"].startswith("https://"), (name, j)
                    assert j["system"] == name and j["id"]


def test_jobvite_follows_next_page():
    with fakenet.serve(ROUTES):
        jobs = B.jobvite("acme-internal")
    assert [j["id"] for j in jobs] == ["oltHAfwP", "oo2uAfwe", "oPage2Job"]
    assert jobs[0]["title"] == "Senior Account Executive" and jobs[0]["location"] == "Santa Barbara, CA"


def test_lever_tells_a_missing_board_from_an_empty_one():
    with fakenet.serve(ROUTES):
        assert B.lever("quiet") == []                 # real board, nothing open
        with pytest.raises(NotFound):                 # board no longer exists
            B.lever("ghost")


def test_paylocity_reads_the_list_inside_the_page():
    with fakenet.serve(ROUTES):
        jobs = B.paylocity("5e5fc082-a90b-4d93-8b73-46f77d40e081")
    assert [(j["id"], j["title"]) for j in jobs] == [("4375500", "Assistant Portfolio Manager"),
                                                      ("4561431", "Director of Marketing")]   # internal-only skipped
    assert jobs[0]["url"] == "https://recruiting.paylocity.com/Recruiting/Jobs/Details/4375500"
    assert jobs[0]["location"] == "Kansas City, MO" and jobs[0]["posted"] == "2026-10-08"
    assert jobs[1]["location"] == "Remote · Denver, CO"


def test_icims_pages_until_a_page_adds_nothing():
    with fakenet.serve(ROUTES) as calls:
        jobs = B.icims("careers-acme", host="careers-acme.icims.com")
    assert [j["id"] for j in jobs] == ["14675", "14658", "14601"]
    assert jobs[0]["title"] == "Account Rep I" and jobs[0]["location"] == "US-MA-Boston"
    assert jobs[0]["url"] == "https://careers-acme.icims.com/jobs/14675/account-rep-i/job"
    assert sum("pr=" in c for c in calls) == 3      # pages 0, 1, then the empty page 2


def test_breezy_on_a_company_address():
    with fakenet.serve(ROUTES):
        jobs = B.breezy("jobs.acmehomes.com", origin="https://jobs.acmehomes.com")
    assert [j["title"] for j in jobs] == ["Photographer"]


def test_workday_keeps_relative_date_and_requisition():
    with fakenet.serve(ROUTES):
        jobs = B.workday("acme", wd="wd5", site="External")
    assert len(jobs) == 2 and jobs[0]["posted_rel"] == "Posted 3 Days Ago" and jobs[0]["ref"] == "R0012345"
    assert jobs[0]["url"] == "https://acme.wd5.myworkdayjobs.com/External/job/Remote/Director--Investments_R0012345"


def test_missing_board_is_an_error_not_an_empty_list():
    """Where the job system answers 404 for an unknown board, the reader must say
    "missing", never "no openings"."""
    with fakenet.serve(ROUTES):
        for name in ("greenhouse", "ashby", "workable", "rippling", "paylocity"):
            with pytest.raises(FetchError):
                B.READERS[name]("no-such-board")


