def test_classify_is_fast_on_very_long_addresses():
    import time
    started = time.time()
    B.classify("https://jobs.lever.co/" + "a" * 20000)
    B.classify("https://example.com/?token=" + "a" * 20000)
    assert time.time() - started < 0.5


